def _unsupported_placeholders(template: str) -> set[str]:
    names = set(re.findall(r"\{([A-Za-z_][A-Za-z0-9_]*)\}", template))
    return {name for name in names if name not in ALLOWED_PLACEHOLDERS and not name.startswith("param_")}


def _normalize_input_roles(spec: dict[str, Any]) -> dict[str, Any]:
    raw = spec.get("input_roles")
    if not isinstance(raw, dict):
        inputs = spec.get("inputs")
        if isinstance(inputs, dict):
            candidate = inputs.get("input_roles") or inputs.get("roles")
            raw = candidate if isinstance(candidate, dict) else {}
        else:
            raw = {}
    normalized: dict[str, Any] = {}
    for placeholder, role_spec in raw.items():
        key = str(placeholder or "").strip().strip("{}")
        if key not in ALLOWED_PLACEHOLDERS or key in {"code_dir", "input_dir", "output_dir", "work_dir"}:
            continue
        if isinstance(role_spec, dict):
            item = dict(role_spec)
        else:
            item = {"role": str(role_spec)}
        item.setdefault("role", "")
        item.setdefault("resolve_by", "")
        item.setdefault("required", True)
        normalized[key] = item
    return normalized


def _normalize_spec_parameters(parameters: dict[str, Any], template: str) -> dict[str, Any]:
    normalized: dict[str, Any] = {}
    used = set(re.findall(r"\{param_([A-Za-z_][A-Za-z0-9_]*)\}", template or ""))
    for raw_name, raw_value in (parameters or {}).items():
        name = _safe_parameter_name(raw_name)
        if not name:
            continue
        if isinstance(raw_value, dict):
            item = dict(raw_value)
        else:
            item = {"default": raw_value}
        editable = bool(item.get("editable", True))
        if editable and name not in used:
            raise ApiConversionError(
                "DeepSeek conversion marked editable parameter without command_template placeholder: "
                f"{name} (expected {{param_{name}}})"
            )
        item.setdefault("editable", editable)
        normalized[name] = item
    return normalized


def _safe_parameter_name(value: Any) -> str:
    text = re.sub(r"[^A-Za-z0-9_]+", "_", str(value or "").strip())
    text = re.sub(r"_+", "_", text).strip("_")
    if not text:
        return ""
    if text[0].isdigit():
        text = "p_" + text
    if text.startswith("param_"):
        text = text[6:]
    return text


def _redact_base_url(value: str) -> str:
    return value.split("?", 1)[0]
