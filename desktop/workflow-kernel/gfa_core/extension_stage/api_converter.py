def _parse_json_object(content: str) -> Any:
    try:
        spec, actions = extract_json_object(content)
        if actions:
            spec["sanitizer_actions"] = list(spec.get("sanitizer_actions") or []) + actions
        return spec
    except ExtensionSpecSanitizerError as exc:
        raise ApiConversionError(f"DeepSeek API response was malformed JSON: {exc}", raw_response=content, code="malformed_json") from exc


