def _deepseek_client() -> tuple[Any, str, str]:
    _load_deepseek_env()
    api_key = os.environ.get("DEEPSEEK_API_KEY", "").strip()
    if not api_key:
        raise ApiConversionError("DEEPSEEK_API_KEY is not configured in ~/gene-family-mas-v2/.env.")

    try:
        from openai import OpenAI
    except Exception as exc:  # pragma: no cover - environment dependent
        raise ApiConversionError(f"OpenAI-compatible client is unavailable: {exc}") from exc

    base_url = os.environ.get("DEEPSEEK_BASE_URL", "https://api.deepseek.com").strip() or "https://api.deepseek.com"
    model = (
        os.environ.get("V15_RELATION_LLM_MODEL")
        or os.environ.get("DEEPSEEK_MODEL")
        or DEFAULT_MODEL
    )
    return OpenAI(api_key=api_key, base_url=base_url, timeout=90, max_retries=0), base_url, model


def _load_deepseek_env() -> None:
    for env_file in (MAS_PROJECT_ROOT / ".env.v15_deepseek", MAS_PROJECT_ROOT / ".env", MAS_PROJECT_ROOT / "config/.env"):
        if not env_file.exists():
            continue
        for raw in env_file.read_text(encoding="utf-8", errors="ignore").splitlines():
            line = raw.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            if line.startswith("export "):
                line = line[len("export ") :].strip()
            key, value = line.split("=", 1)
            key = key.strip()
            value = value.strip().strip("\"'")
            if key:
                os.environ.setdefault(key, value)


