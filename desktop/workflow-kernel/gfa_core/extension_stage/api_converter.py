class ApiConversionError(RuntimeError):
    """Raised when the required API conversion path is unavailable or invalid."""

    def __init__(self, message: str, *, raw_response: str = "", code: str = "") -> None:
        super().__init__(message)
        self.raw_response = raw_response
        self.code = code


def convert_with_deepseek_api(
    *,
    display_name: str,
    raw_code: Path,
    raw_data: Path,
    runtime_env: str,
    lessons: list[dict[str, Any]] | None = None,
) -> dict[str, Any]:
    """Return a conversion spec generated by the DeepSeek API.

    The returned dict must contain at least ``original_command`` and
    ``command_template``.  Placeholders allowed in ``command_template`` are:
    ``{code_dir}``, ``{input_dir}``, ``{input_file}``, ``{input_hmm}``,
    ``{input_fasta}``, ``{input_query_fasta}``, ``{input_reference_fasta}``,
    ``{input_pep_fasta}``, ``{input_cds_fasta}``, ``{input_id_file}``,
    ``{output_dir}``, ``{work_dir}``, and controlled
    parameter placeholders named ``{param_<parameter_name>}``.
    """

    client, base_url, model = _deepseek_client()
    prompt = _build_conversion_prompt(display_name=display_name, raw_code=raw_code, raw_data=raw_data, runtime_env=runtime_env, lessons=lessons or [])
    try:
        response = client.chat.completions.create(
            model=model,
            messages=[
                {
                    "role": "system",
                    "content": (
                        "You convert already-runnable bioinformatics code into a bbav5 lightweight "
                        "extension analysis stage. Return strict JSON only. Do not include markdown."
                    ),
                },
                {"role": "user", "content": prompt},
            ],
            temperature=0,
            max_tokens=6000,
        )
    except Exception as exc:
        raise ApiConversionError(f"DeepSeek API conversion failed: {exc}") from exc

    content = (response.choices[0].message.content or "").strip()
    spec = _parse_json_object(content)
    if not isinstance(spec, dict):
        raise ApiConversionError("DeepSeek API did not return a JSON object.")
    spec["converter"] = {
        "type": "deepseek_api",
        "project_root": str(MAS_PROJECT_ROOT),
        "base_url": _redact_base_url(base_url),
        "model": model,
    }
    return spec


