#!/usr/bin/env Rscript
# Rscript community_stats.R relative_abundance.tsv samples.csv outdir
suppressPackageStartupMessages(library(vegan))
a <- commandArgs(trailingOnly=TRUE)
if (length(a) != 3) stop("Need relative_abundance.tsv samples.csv outdir")
x <- t(as.matrix(read.delim(a[1],row.names=1,check.names=FALSE)))
m <- read.csv(a[2],stringsAsFactors=FALSE)
if (!all(c("sample_id","donor","group") %in% names(m))) stop("Missing metadata")
if (anyDuplicated(m$sample_id) || anyDuplicated(m$donor)) stop("Independent donors only")
if (!setequal(rownames(x),m$sample_id)) stop("Sample mismatch")
if (any(!is.finite(x)) || any(x<0) || any(rowSums(x)<=0)) stop("Invalid abundance")
rownames(m) <- m$sample_id; m <- m[rownames(x),,drop=FALSE]
m$group <- factor(m$group)
if (nlevels(m$group)<2 || any(table(m$group)<3)) stop("Need >=2 groups, >=3 independent samples/group")
if (dir.exists(a[3]) && length(list.files(a[3],all.files=TRUE,no..=TRUE))) stop("Output must be empty")
dir.create(a[3],recursive=TRUE,showWarnings=FALSE)
x <- x/rowSums(x)
set.seed(42)
d <- vegdist(x,method="bray")
test <- adonis2(d ~ group,data=m,permutations=999)
disp <- betadisper(d,group=m$group,type="median",bias.adjust=TRUE)
disp_test <- permutest(disp,permutations=999)
write.table(as.data.frame(test),file.path(a[3],"permanova.tsv"),sep="\t",quote=FALSE)
write.table(as.data.frame(disp_test$tab),file.path(a[3],"dispersion_test.tsv"),sep="\t",quote=FALSE)
capture.output(sessionInfo(),file=file.path(a[3],"sessionInfo.txt"))
